const fs=require('node:fs'),assert=require('node:assert/strict');
let s=fs.readFileSync('overrides/appmenu/portalOwners.js','utf8').replace(/^import .*;$/gm,'').replace(/^export /gm,'');
const find=new Function(s+';return portalOwnerId;')();
const a={pid:123,title:'Choose file',appId:'org.example.App'};
assert.equal(find([a],123,'Choose file'),'org.example.App');
assert.equal(find([a],124,'Choose file'),null);
assert.equal(find([a],123,'Other'),null);
assert.equal(find([a,{...a,appId:'org.other.App'}],123,'Choose file'),null);
assert.equal(find([],123,'Choose file'),null);
assert.equal(find({},123,'Choose file'),null);
assert.equal(find([null],123,'Choose file'),null);
console.log('Portal match: exact PID and title, ambiguous/stale/malformed records fail closed PASS');
const proxy={shellPid:777,wmClass:'xdg-desktop-portal-gnome',windowCount:1};
const b={...a,backendClass:proxy.wmClass};
assert.equal(find([b],777,a.title,proxy),a.appId);
assert.equal(find([b],778,a.title,proxy),null);
assert.equal(find([b],777,a.title,{...proxy,wmClass:'ordinary-app'}),null);
assert.equal(find([b],777,a.title,{...proxy,windowCount:2}),null);
assert.equal(find([b,{...b,appId:'org.second.App'}],777,a.title,proxy),null);
assert.equal(find([b],777,'Different title',proxy),null);
assert.equal(find([a],777,a.title,proxy),null);
assert.equal(find([],777,a.title,proxy),null);
assert.equal(find([{...b,backendClass:'xdg-desktop-portal-gtk'}],777,a.title,proxy),null);
console.log('Portal compositor socket: exact backend, unique request/window, no ordinary-window or stale fallback PASS');
